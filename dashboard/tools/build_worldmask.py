"""Build dashboard/static/vendor/worldmask.js, the offline land mask behind the attack map.

Source: world-atlas 2.0.2 `land-110m.json` (Natural Earth 1:110m land, public domain; world-atlas is ISC licensed).
Fetch it with `npm pack world-atlas@2.0.2 && tar xzf world-atlas-2.0.2.tgz`, then run:

    python dashboard/tools/build_worldmask.py package

The output is one hex string per latitude row of an equirectangular grid (bit set = land), so the map draws real
continents with no network access and no tile server: a 1.5 degree world grid (land-110m) and a 0.4 degree grid of
Europe (land-50m) for the cyber range's zoomed map.
"""
import json
import os
import sys

import numpy as np

MASKS = [  # name, source file, degrees per cell, lat top, lat bottom, lng min, lng max
    ("world", "land-110m.json", 1.5, 84.0, -58.0, -180.0, 180.0),
    ("europe", "land-50m.json", 0.4, 60.0, 33.0, -14.0, 36.0),
]
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "static", "vendor", "worldmask.js")


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    return arcs


def ring_points(ring, arcs):
    pts = []
    for i in ring:
        a = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
        pts.extend(a if not pts else a[1:])
    return pts


def rings_of(topo, arcs):
    out = []
    def geom(g):
        if g["type"] == "GeometryCollection":
            for h in g["geometries"]:
                geom(h)
        elif g["type"] == "Polygon":
            out.extend(ring_points(r, arcs) for r in g["arcs"])
        elif g["type"] == "MultiPolygon":
            for poly in g["arcs"]:
                out.extend(ring_points(r, arcs) for r in poly)
    for obj in topo["objects"].values():
        geom(obj)
    return out


def land_grid(rings, lats, lngs):
    """Even-odd ray casting for every grid point at once, ring by ring (numpy)."""
    gx, gy = np.meshgrid(lngs, lats)
    px, py = gx.ravel(), gy.ravel()
    hit = np.zeros(px.shape, dtype=bool)
    for ring in rings:
        r = np.asarray(ring)
        if r[:, 0].max() < lngs.min() or r[:, 0].min() > lngs.max() or r[:, 1].max() < lats.min() or r[:, 1].min() > lats.max():
            continue
        x1, y1 = r[:, 0], r[:, 1]
        x2, y2 = np.roll(x1, 1), np.roll(y1, 1)
        for i in range(0, len(x1), 512):
            a1, b1, a2, b2 = x1[i:i + 512, None], y1[i:i + 512, None], x2[i:i + 512, None], y2[i:i + 512, None]
            crosses = (b1 > py) != (b2 > py)
            with np.errstate(divide="ignore", invalid="ignore"):
                xint = (a2 - a1) * (py - b1) / (b2 - b1) + a1
            hit ^= (np.count_nonzero(crosses & (px < xint), axis=0) % 2).astype(bool)
    return hit.reshape(len(lats), len(lngs))


def build(folder, name, src, step, lat_top, lat_bottom, lng_min, lng_max):
    with open(os.path.join(folder, src), encoding="utf-8") as fh:
        topo = json.load(fh)
    rings = rings_of(topo, decode_arcs(topo))
    lats = np.arange(lat_top - step / 2, lat_bottom, -step)
    lngs = lng_min + step * (np.arange(int(round((lng_max - lng_min) / step))) + 0.5)
    grid = land_grid(rings, lats, lngs)
    rows = []
    for row in grid:
        bits = "".join("1" if v else "0" for v in row)
        bits += "0" * (-len(bits) % 4)
        rows.append("%0*x" % (len(bits) // 4, int(bits, 2)))
    print(f"{name}: {len(rows)} rows x {len(lngs)} cols from {src}")
    return {"name": name, "step": step, "latTop": lat_top, "lngMin": lng_min, "cols": int(len(lngs)), "rows": rows}


def main(folder):
    masks = [build(folder, *m) for m in MASKS]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by dashboard/tools/build_worldmask.py from world-atlas 2.0.2 land-110m.json and land-50m.json\n"
                 "// (Natural Earth land, public domain; world-atlas ISC). Equirectangular grids, one hex row per latitude\n"
                 "// band, bit set = land. Do not edit by hand.\n")
        fh.write("window.WORLD_MASKS = " + json.dumps(masks) + ";\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "package")
